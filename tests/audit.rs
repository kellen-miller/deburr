#[test]
fn excluded_and_syntax_error_files_still_get_code_lines() {
    let dir = tempfile::tempdir().expect("temp dir");
    let root = dir.path();
    write(root, "vendor/v.go", "package v\n\n// c\nvar v = 1\n");
    write(root, "web/__tests__/t.ts", "// c\nexport const t = 1;\n");
    write(root, "bad.go", "package a\n\nfunc F( {\n\treturn\n}\n");
    write(root, "bad.ts", "const = ;\n\n// c\nlet y = ;\n");
    write(root, "nopkg.go", "// c\nfunc F() {}\n");

    let outcome = run(root, &options());
    let report = &outcome.report;

    let vendor = file(report, "vendor/v.go");
    assert_eq!(vendor.status, FileStatus::Excluded);
    assert_eq!((vendor.lines, vendor.code_lines), (4, 2));

    let excluded_ts = run(
        root,
        &AuditOptions {
            include_tests: false,
            ..options()
        },
    );
    let typescript = file(&excluded_ts.report, "web/__tests__/t.ts");
    assert_eq!(typescript.status, FileStatus::Excluded);
    assert_eq!((typescript.lines, typescript.code_lines), (2, 1));

    let failures = [
        ParseFailure {
            path: "bad.go",
            message: "syntax error at ",
            lines: 5,
        },
        ParseFailure {
            path: "bad.ts",
            message: "syntax error at ",
            lines: 4,
        },
        ParseFailure {
            path: "nopkg.go",
            message: "syntax error at ",
            lines: 2,
        },
    ];

    for failure in &failures {
        let entry = file(report, failure.path);

        assert_eq!(entry.status, FileStatus::ParseError, "{}", failure.path);
        assert_eq!(entry.lines, failure.lines, "{}", failure.path);
        assert!(
            entry.code_lines > 0,
            "{} keeps its code-line count",
            failure.path
        );
        assert!(entry.error.starts_with(failure.message), "{}", failure.path);
    }

    assert_eq!(file(report, "nopkg.go").code_lines, 1);
    assert_eq!(file(report, "bad.ts").code_lines, 2);
    assert_eq!(
        excluded_ts.report.metrics.all.code_lines, 0,
        "only analyzed files feed metrics"
    );
}

#[test]
fn manifest_digest_tracks_every_discovered_file() {
    let dir = tempfile::tempdir().expect("temp dir");
    write(dir.path(), "a.go", GO_SOURCE);
    write(dir.path(), "notes.md", "one\n");

    let first = run(dir.path(), &options()).report;
    let again = run(dir.path(), &options()).report;
    let digest = |report: &Report| report.provenance.source.manifest_digest.clone();

    assert!(digest(&first).starts_with("sha256:"));
    assert_eq!(digest(&first), digest(&again));

    write(dir.path(), "a.go", "package a\n");
    let edited = run(dir.path(), &options()).report;

    assert_ne!(digest(&first), digest(&edited));
}

#[test]
fn audits_are_deterministic_and_attach_a_ledger() {
    let dir = tempfile::tempdir().expect("temp dir");
    for index in 0..40 {
        write(dir.path(), &format!("p{index}/f.go"), GO_SOURCE);
        write(
            dir.path(),
            &format!("p{index}/g.ts"),
            "export const x = 1;\n",
        );
    }

    let first = run(dir.path(), &options()).report;
    let second = run(dir.path(), &options()).report;

    assert_eq!(
        serde_json::to_string(&first).expect("encode"),
        serde_json::to_string(&second).expect("encode"),
    );
    assert!(first.review.is_some());
    assert_eq!(first.coverage.analyzed, 80);
    assert_eq!(first.provenance.build.version, deburr::VERSION);
}

