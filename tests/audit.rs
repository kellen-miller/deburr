//! Discovery, parsing, line counts, and the audit pipeline, driven through
//! the library on temporary trees.

use std::fs;
use std::path::Path;

use deburr::audit::{AuditOptions, AuditOutcome, audit};
use deburr::report::{Category, File, FileStatus, Report};
use deburr::syntax::{self, Language};

const GO_SOURCE: &str = "package a\n\nfunc F() int {\n\treturn 1\n}\n";

fn options() -> AuditOptions {
    AuditOptions {
        include_tests: true,
        include_testdata: false,
        include_vendor: false,
        include_generated: false,
        max_file_bytes: None,
        duplication: None,
    }
}

/// What a report should say about one discovered file.
struct Expectation {
    path: &'static str,
    category: Category,
    status: FileStatus,
    reason: &'static str,
}

fn expect(
    path: &'static str,
    category: Category,
    status: FileStatus,
    reason: &'static str,
) -> Expectation {
    Expectation {
        path,
        category,
        status,
        reason,
    }
}

/// A file that must fail to parse, with the line count it still reports.
struct ParseFailure {
    path: &'static str,
    message: &'static str,
    lines: u32,
}

fn write(root: &Path, relative: &str, contents: &str) {
    let path = root.join(relative);

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).expect("create parent directories");
    }

    fs::write(path, contents).expect("write fixture");
}

fn run(root: &Path, options: &AuditOptions) -> AuditOutcome {
    audit(root, options, &mut std::io::sink())
}

fn file<'a>(report: &'a Report, path: &str) -> &'a File {
    report
        .files
        .iter()
        .find(|file| file.path == path)
        .unwrap_or_else(|| panic!("report has no file {path}"))
}

/// The text of every code token, including synthetic terminators, whether or
/// not the file is syntactically valid.
fn token_texts(language: Language, source: &str) -> Vec<String> {
    let parsed = syntax::parse(language, source.as_bytes().to_vec())
        .or_else(|error| error.recovered().map_err(|_| ()))
        .expect("tree-sitter produces a tree");

    parsed
        .tokens
        .iter()
        .map(|token| String::from_utf8_lossy(parsed.token_text(token)).into_owned())
        .collect()
}

fn syntax_error(language: Language, source: &str) -> Option<String> {
    syntax::parse(language, source.as_bytes().to_vec())
        .err()
        .map(|error| error.to_string())
}

#[test]
fn categories_statuses_and_reasons() {
    let dir = tempfile::tempdir().expect("temp dir");
    let root = dir.path();
    write(root, "a.go", GO_SOURCE);
    write(root, "a_test.go", GO_SOURCE);
    write(root, "vendor/v.go", GO_SOURCE);
    write(root, "testdata/t.go", GO_SOURCE);
    write(
        root,
        "gen.go",
        "// Code generated by tool. DO NOT EDIT.\n\npackage a\n",
    );
    write(root, "web/x.ts", "export const x = 1;\n");
    write(root, "web/x.test.ts", "export const y = 1;\n");
    write(root, "web/x.spec.tsx", "export const z = <div />;\n");
    write(root, "web/__tests__/y.ts", "export const w = 1;\n");
    write(root, "types/api.d.ts", "export declare const a: number;\n");
    write(root, "README.md", "# notes\n");
    write(root, "node_modules/skip.go", GO_SOURCE);
    write(root, ".git/config", "x\n");
    write(root, "pkg/.worktrees/w.go", GO_SOURCE);

    let report = run(root, &options()).report;

    let expected = [
        expect("a.go", Category::Production, FileStatus::Analyzed, ""),
        expect("a_test.go", Category::Test, FileStatus::Analyzed, ""),
        expect(
            "vendor/v.go",
            Category::Vendor,
            FileStatus::Excluded,
            "vendor excluded by configuration",
        ),
        expect(
            "testdata/t.go",
            Category::Testdata,
            FileStatus::Excluded,
            "testdata excluded by configuration",
        ),
        expect(
            "gen.go",
            Category::Generated,
            FileStatus::Excluded,
            "generated excluded by configuration",
        ),
        expect("web/x.ts", Category::Production, FileStatus::Analyzed, ""),
        expect("web/x.test.ts", Category::Test, FileStatus::Analyzed, ""),
        expect("web/x.spec.tsx", Category::Test, FileStatus::Analyzed, ""),
        expect(
            "web/__tests__/y.ts",
            Category::Test,
            FileStatus::Analyzed,
            "",
        ),
        expect(
            "types/api.d.ts",
            Category::Production,
            FileStatus::Analyzed,
            "",
        ),
        expect(
            "README.md",
            Category::Production,
            FileStatus::Unsupported,
            "language is not supported",
        ),
    ];

    for expectation in &expected {
        let entry = file(&report, expectation.path);

        assert_eq!(
            entry.category, expectation.category,
            "{} category",
            expectation.path
        );
        assert_eq!(
            entry.status, expectation.status,
            "{} status",
            expectation.path
        );
        assert_eq!(
            entry.reason, expectation.reason,
            "{} reason",
            expectation.path
        );
    }

    assert_eq!(
        report.files.len(),
        expected.len(),
        "skipped dirs are not files"
    );
    assert_eq!(report.coverage.excluded_directories, 3);
    assert_eq!(report.coverage.discovered, 11);
    assert_eq!(report.coverage.analyzed, 7);
    assert_eq!(report.coverage.excluded, 3);
    assert_eq!(report.coverage.unsupported, 1);

    let order: Vec<Category> = report
        .coverage
        .by_category
        .iter()
        .map(|row| row.category)
        .collect();
    assert_eq!(order, Category::ALL);
}

