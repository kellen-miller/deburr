#[test]
fn audit_reports_structural_go_errors_as_parse_errors() {
    let dir = tempfile::tempdir().expect("temp dir");
    write(dir.path(), "nopkg.go", "func F() {}\n");
    write(dir.path(), "stmt.go", "package a\n\nx := 1\n");

    let outcome = run(dir.path(), &options());

    let failures = [
        ParseFailure {
            path: "nopkg.go",
            message: "syntax error at 1:1",
            lines: 1,
        },
        ParseFailure {
            path: "stmt.go",
            message: "syntax error at 3:1",
            lines: 3,
        },
    ];

    for failure in &failures {
        let entry = file(&outcome.report, failure.path);

        assert_eq!(entry.status, FileStatus::ParseError, "{}", failure.path);
        assert_eq!(entry.error, failure.message, "{}", failure.path);
        assert_eq!(entry.lines, failure.lines, "{}", failure.path);
    }

    assert_eq!(outcome.report.coverage.parse_errors, 2);
    assert_eq!(outcome.errors.len(), 2);
    assert_eq!(
        outcome.errors[0].to_string(),
        "nopkg.go: syntax error at 1:1"
    );
}

#[test]
fn invalid_octal_literal_is_reported_as_a_syntax_error() {
    // Documents actual behavior: go/parser rejects `08` for its digits, and
    // tree-sitter-go splits it into `0` and `8`, which is an ERROR node, so
    // both versions report a parse error here. Other lexical-validity gaps
    // (for example out-of-range escapes) are not re-checked and are accepted
    // divergences.
    assert_eq!(
        syntax_error(Language::Go, "package a\n\nvar x = 08\n").as_deref(),
        Some("syntax error at 3:9")
    );
}

#[test]
fn semicolon_insertion_changes_token_text() {
    let split = token_texts(
        Language::Go,
        "package a\n\nfunc f() int {\n\treturn\n\tg()\n}\n",
    );
    let joined = token_texts(
        Language::Go,
        "package a\n\nfunc f() int {\n\treturn g()\n}\n",
    );

    assert_ne!(split, joined);
    assert!(
        split.join(" ").contains("return ; g ( ) ;"),
        "return is its own statement: {split:?}"
    );
    assert!(
        joined.join(" ").contains("return g ( ) ;"),
        "return takes g(): {joined:?}"
    );
}

#[test]
fn explicit_and_implicit_terminators_tokenize_alike() {
    assert_eq!(
        token_texts(
            Language::Go,
            "package a\n\nfunc f() {\n\tx := 1; y := 2\n}\n"
        ),
        token_texts(
            Language::Go,
            "package a\n\nfunc f() {\n\tx := 1\n\ty := 2\n}\n"
        ),
    );
    assert_eq!(
        token_texts(Language::TypeScript, "function f() {\n  a();\n  b()\n}\n"),
        token_texts(Language::TypeScript, "function f() {\n  a()\n  b();\n}\n"),
    );
    assert_eq!(
        token_texts(Language::TypeScript, "a(); b()\n"),
        ["a", "(", ")", ";", "b", "(", ")", ";"]
    );
}

#[test]
fn string_like_nodes_are_single_tokens() {
    let go = token_texts(
        Language::Go,
        "package a\n\nvar s = \"a b\" + `c\nd` + 'e'\n",
    );

    assert!(go.contains(&"\"a b\"".to_owned()), "{go:?}");
    assert!(go.contains(&"`c\nd`".to_owned()), "{go:?}");
    assert!(go.contains(&"'e'".to_owned()), "{go:?}");

    let ts = token_texts(Language::TypeScript, "const s = `abc` + \"x\" + /re+/g;\n");

    assert!(ts.contains(&"`abc`".to_owned()), "{ts:?}");
    assert!(ts.contains(&"\"x\"".to_owned()), "{ts:?}");
    assert!(ts.contains(&"/re+/g".to_owned()), "{ts:?}");
}

#[test]
fn template_literals_with_substitutions_are_tokenized_by_their_leaves() {
    // A template literal without a substitution is one token, but `${..}`
    // holds code: a function written there must have tokens of its own to be
    // measured, so the literal is split around it.
    let ts = token_texts(Language::TypeScript, "const s = `a${b}c`;\n");

    assert!(!ts.contains(&"`a${b}c`".to_owned()), "{ts:?}");
    assert_eq!(
        ts,
        ["const", "s", "=", "`", "a", "${", "b", "}", "c", "`", ";"]
    );
}

