func TestAnalyzeCountsBranchShortCircuitAndDefaultSwitch(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "decisions.go", `package sample

func Decisions(value int) int {
	if value > 0 && value < 10 {
		return 1
	}
	switch value {
	default:
		return 0
	}
}
`)

	result := analyze(t, root)
	function := functionByName(t, result, "Decisions")

	if function.Cyclomatic != 3 {
		t.Fatalf("Decisions cyclomatic complexity = %d, want 3 (base + if + short-circuit)", function.Cyclomatic)
	}

	if function.MaxNesting != 1 {
		t.Fatalf("Decisions max nesting = %d, want 1", function.MaxNesting)
	}
}

func TestAnalyzeAccountsNestedClosureAndSkipsNoBodyDeclaration(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "closures.go", `package sample

func Outer(value int) int {
	total := 0
	total += func() int {
		if value > 0 {
			return 1
		}
		return 2
	}()
	return total
}

func Declared()
`)

	result := analyze(t, root)
	outer := functionByName(t, result, "Outer")
	closure := functionByName(t, result, "Outer.func1")

	if outer.SLOC != 4 {
		t.Fatalf("Outer SLOC = %d, want 4 lines owned outside the closure", outer.SLOC)
	}

	if closure.SLOC != 6 {
		t.Fatalf("Outer.func1 SLOC = %d, want 6 closure lines", closure.SLOC)
	}

	if outer.SLOC+closure.SLOC != 10 {
		t.Fatalf("nested function SLOC = %d, want 10", outer.SLOC+closure.SLOC)
	}

	if len(result.Functions) != 2 {
		t.Fatalf("function count = %d, want only Outer and its closure", len(result.Functions))
	}
}

