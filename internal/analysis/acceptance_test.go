func TestAnalyzeUsesPhysicalPositionsForLineDirectives(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "directive.go", `package sample

//line virtual.go:100
func Directive(value int) bool {
	if value > 0 {
		return true
	}
	return false
}
`)

	result := analyze(t, root)
	function := functionByName(t, result, "Directive")

	if function.Path != "directive.go" {
		t.Fatalf("directive function path = %q, want physical path directive.go", function.Path)
	}

	if function.Start.Line != 4 || function.End.Line != 9 {
		t.Fatalf("directive function lines = %d-%d, want physical lines 4-9", function.Start.Line, function.End.Line)
	}

	if function.SLOC != 6 {
		t.Fatalf("directive function SLOC = %d, want physical lines 4-9", function.SLOC)
	}
}

